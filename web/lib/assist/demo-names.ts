function looksLikePatientName(text: string): boolean {
  const pattern = /\bpatient\s+([a-z][a-z'-]+)\s+([a-z][a-z'-]+)\b/gi;
  for (const match of text.matchAll(pattern)) {
    const first = (match[1] ?? "").toLowerCase();
    const second = (match[2] ?? "").toLowerCase();
    if (!PATIENT_STOP.has(first) && !PATIENT_STOP.has(second)) return true;
  }
  return false;
}

/** True when the text still contains an identifier after the demo cast is removed. */
export function assistHasPersonalIdentifier(text: string): boolean {
  let rest = text;
  for (const name of DEMO_CAST) {
    rest = rest.replace(new RegExp(`\\b${escapeName(name)}\\b`, "gi"), " ");
  }
  if (looksLikePatientName(rest)) return true;
  return textHasPersonalIdentifier(rest);
}
